import { TaskItem } from './TaskItem.jsx';
import './TaskList.css';

export function TaskList({ tasks, onToggle, onEdit, onDelete }) {
  return (
    <ul className="task-list">
      {tasks.map((task) => (
        <TaskItem
          key={task.id}
          task={task}
          onToggle={onToggle}
          onEdit={onEdit}
          onDelete={onDelete}
        />
      ))}
    </ul>
  );
}
